def gen_sha256() -> None:
    cases = [
        ("empty", b"", "the empty octet string"),
        ("abc", b"abc", "NIST FIPS 180-4 example"),
        ("fox", b"The quick brown fox jumps over the lazy dog", "classic pangram"),
        ("canonical-empty-object", b"{}", "SHA-256 of the canonical empty object"),
        ("bytes-00-01-ff", bytes([0x00, 0x01, 0xFF]), "non-UTF-8 octets"),
        ("block-boundary-64", b"a" * 64, "exactly one compression block"),
        ("block-boundary-55", b"a" * 55, "maximum single-block message with padding"),
        ("block-boundary-56", b"a" * 56, "first length needing a second block"),
    ]
    # Known answers that MUST hold (FIPS 180-4 / universally published).
    known = {
        "empty": "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
        "abc": "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
    }
    vectors = []
    for name, data, desc in cases:
        digest = sha256_hex(data)
        if name in known:
            assert digest == known[name], f"sha256 {name}: {digest} != published {known[name]}"
        vectors.append(
            {"name": name, "description": desc, "input-hex": data.hex(), "sha256": digest}
        )
    emit(
        "sha256.json",
        "sha256",
        "SHA-256 known-answer tests. Hash the octets of `input-hex`; result MUST equal `sha256`.",
        vectors,
    )


