def gen_jcs_invalid() -> None:
    cases = [
        ("duplicate-key", '{"a":1,"a":2}', "jcs-duplicate-key", "duplicate member names are forbidden"),
        (
            "duplicate-key-nested",
            '{"o":{"x":1,"x":1}}',
            "jcs-duplicate-key",
            "duplicates are rejected at any depth, even with equal values",
        ),
        ("lone-high-surrogate", '{"a":"\\ud800"}', "jcs-lone-surrogate", "unpaired high surrogate"),
        ("lone-low-surrogate", '{"a":"\\udc00x"}', "jcs-lone-surrogate", "unpaired low surrogate"),
        (
            "lone-surrogate-in-name",
            '{"\\ud83d":1}',
            "jcs-lone-surrogate",
            "an unpaired surrogate in a member name is equally invalid",
        ),
        ("nan-literal", '{"a":NaN}', "jcs-malformed-json", "NaN is not an RFC 8259 literal"),
        ("infinity-literal", '{"a":Infinity}', "jcs-malformed-json", "Infinity is not an RFC 8259 literal"),
        (
            "number-overflows-binary64",
            '{"a":1e400}',
            "jcs-malformed-json",
            "a literal outside the binary64 range has no canonical form",
        ),
        ("trailing-comma", '{"a":1,}', "jcs-malformed-json", "trailing commas are not JSON"),
        ("unquoted-name", "{a:1}", "jcs-malformed-json", "member names must be strings"),
        ("single-quotes", "{'a':1}", "jcs-malformed-json", "single quotes are not JSON"),
        ("truncated", '{"a":', "jcs-malformed-json", "truncated input"),
        ("empty-input", "", "jcs-malformed-json", "empty input is not a JSON value"),
    ]
    vectors = []
    for name, raw, code, desc in cases:
        try:
            parse_json_strict(raw)
        except JcsError as exc:
            assert exc.code == code, f"{name}: generator produced {exc.code}, expected {code}"
        else:
            raise AssertionError(f"{name}: generator accepted invalid input")
        vectors.append({"name": name, "description": desc, "input-json": raw, "error": code})
    emit(
        "jcs-invalid.json",
        "jcs-invalid",
        "Inputs a conformant canonicalizer MUST reject, with the normative error code "
        "(spec 01 section 3.1). Parsing `input-json` MUST fail with `error`.",
        vectors,
    )


