# --------------------------------------------------------------------------
# JCS (RFC 8785) -- spec 01 section 3
# --------------------------------------------------------------------------


class JcsError(Exception):
    def __init__(self, code: str) -> None:
        self.code = code
        super().__init__(code)


def _pairs_hook(pairs):
    seen = set()
    for k, _ in pairs:
        if k in seen:
            raise JcsError("jcs-duplicate-key")
        seen.add(k)
    return dict(pairs)


def _reject_constant(_name):
    # NaN / Infinity / -Infinity are not RFC 8259 literals.
    raise JcsError("jcs-malformed-json")


def _check_str(s: str) -> None:
    try:
        s.encode("utf-8")
    except UnicodeEncodeError:
        raise JcsError("jcs-lone-surrogate")


def _check_value(v: Any) -> None:
    if v is None or v is True or v is False:
        return
    if isinstance(v, str):
        _check_str(v)
    elif isinstance(v, int):
        try:
            f = float(v)
        except OverflowError:
            raise JcsError("jcs-malformed-json")
        if math.isinf(f):
            raise JcsError("jcs-malformed-json")
    elif isinstance(v, float):
        if math.isnan(v) or math.isinf(v):
            raise JcsError("jcs-malformed-json")
    elif isinstance(v, dict):
        for k, val in v.items():
            _check_str(k)
            _check_value(val)
    elif isinstance(v, list):
        for x in v:
            _check_value(x)
    else:
        raise JcsError("jcs-malformed-json")


def parse_json_strict(text: str) -> Any:
    """Parse JSON text, rejecting what RFC 8785 forbids."""
    try:
        value = json.loads(text, object_pairs_hook=_pairs_hook, parse_constant=_reject_constant)
    except JcsError:
        raise
    except Exception:
        raise JcsError("jcs-malformed-json")
    _check_value(value)
    return value


_ESCAPES = {
    '"': '\\"',
    "\\": "\\\\",
    "\b": "\\b",
    "\f": "\\f",
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
}


def jcs_string(s: str) -> str:
    out = ['"']
    for ch in s:
        esc = _ESCAPES.get(ch)
        if esc is not None:
            out.append(esc)
        elif ord(ch) < 0x20:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def es_number_to_string(x: float) -> str:
    """ECMAScript Number::toString for a finite binary64 (spec 01 section 3.4)."""
    if math.isnan(x) or math.isinf(x):
        raise JcsError("jcs-non-finite-number")
    if x == 0.0:  # also covers -0.0
        return "0"
    sign = "-" if x < 0 else ""
    r = repr(abs(x))  # shortest round-tripping decimal since CPython 3.1
    if "e" in r:
        mant, exp_s = r.split("e")
        exp = int(exp_s)
    else:
        mant, exp = r, 0
    if "." in mant:
        int_part, frac = mant.split(".")
    else:
        int_part, frac = mant, ""
    all_digits = int_part + frac
    stripped = all_digits.lstrip("0")
    lead_zeros = len(all_digits) - len(stripped)
    n = len(int_part) + exp - lead_zeros
    digits = stripped.rstrip("0")
    if digits == "":
        digits = "0"
    k = len(digits)

    if k <= n <= 21:
        return sign + digits + "0" * (n - k)
    if 0 < n <= 21:
        return sign + digits[:n] + "." + digits[n:]
    if -6 < n <= 0:
        return sign + "0." + "0" * (-n) + digits
    e = n - 1
    esign = "+" if e >= 0 else "-"
    if k == 1:
        return sign + digits + "e" + esign + str(abs(e))
    return sign + digits[0] + "." + digits[1:] + "e" + esign + str(abs(e))


def canonicalize(v: Any) -> str:
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, str):
        _check_str(v)
        return jcs_string(v)
    if isinstance(v, int):
        return es_number_to_string(float(v))
    if isinstance(v, float):
        return es_number_to_string(v)
    if isinstance(v, list):
        return "[" + ",".join(canonicalize(x) for x in v) + "]"
    if isinstance(v, dict):
        # Sort by UTF-16 code units: comparing UTF-16BE bytes is equivalent.
        items = sorted(v.items(), key=lambda kv: kv[0].encode("utf-16-be"))
        return "{" + ",".join(jcs_string(k) + ":" + canonicalize(val) for k, val in items) + "}"
    raise JcsError("jcs-malformed-json")


def sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def object_hash(v: Any) -> str:
    return sha256_hex(canonicalize(v).encode("utf-8"))


# --------------------------------------------------------------------------
# Keys and signed objects -- spec 01 sections 4-5
# --------------------------------------------------------------------------


class Key:
    def __init__(self, label: str, seed: bytes) -> None:
        self.label = label
        self.seed = seed
        self.sk = SigningKey(seed)
        self.pk = bytes(self.sk.verify_key)

    @property
    def key_id(self) -> str:
        return "ed25519:" + self.pk.hex()

    def sign(self, msg: bytes) -> bytes:
        return self.sk.sign(msg).signature

    def as_vector(self) -> dict:
        return {
            "label": self.label,
            "secret-key": self.seed.hex(),
            "public-key": self.pk.hex(),
            "key-id": self.key_id,
        }


def named_key(label: str) -> Key:
    seed = hashlib.sha256(("stozher/0.1 test vector key: " + label).encode()).digest()
    return Key(label, seed)


def signing_input(obj: dict) -> str:
    body = {k: v for k, v in obj.items() if k != "sig"}
    return canonicalize(body)


def sign_object(obj: dict, key: Key) -> dict:
    msg = signing_input(obj).encode("utf-8")
    out = dict(obj)
    out["sig"] = {"alg": "ed25519", "key": key.key_id, "value": key.sign(msg).hex()}
    return out


def verify_signed_object(obj: dict) -> bool:
    sig = obj.get("sig")
    if not isinstance(sig, dict) or sig.get("alg") != "ed25519":
        return False
    kid = sig.get("key", "")
    if not (isinstance(kid, str) and kid.startswith("ed25519:") and len(kid) == 72):
        return False
    try:
        vk = VerifyKey(bytes.fromhex(kid[8:]))
        vk.verify(signing_input(obj).encode("utf-8"), bytes.fromhex(sig["value"]))
        return True
    except (BadSignatureError, ValueError):
        return False


# --------------------------------------------------------------------------
# SLIP-0010 (ed25519, hardened only) -- spec 01 section 6
# --------------------------------------------------------------------------

HARDENED = 0x80000000


def slip10_master(seed: bytes) -> tuple[bytes, bytes]:
    i = hmac.new(b"ed25519 seed", seed, hashlib.sha512).digest()
    return i[:32], i[32:]


def slip10_child(k_par: bytes, c_par: bytes, index: int) -> tuple[bytes, bytes]:
    if index < HARDENED:
        raise ValueError("slip10-non-hardened-index")
    data = b"\x00" + k_par + struct.pack(">I", index)
    i = hmac.new(c_par, data, hashlib.sha512).digest()
    return i[:32], i[32:]


def slip10_derive(seed: bytes, path: str) -> tuple[bytes, bytes]:
    k, c = slip10_master(seed)
    if path.strip() == "m":
        return k, c
    for part in path.split("/")[1:]:
        if not part.endswith("'"):
            raise ValueError("slip10-non-hardened-index")
        k, c = slip10_child(k, c, int(part[:-1]) + HARDENED)
    return k, c


def pub_of(priv: bytes) -> bytes:
    return bytes(SigningKey(priv).verify_key)


