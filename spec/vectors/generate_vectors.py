    chain = build_chain(key)
    stream = chain[0]["stream"]
    head = object_hash(chain[-1])

    def checkpoint(**over: Any) -> dict:
        body = {
            "stream": stream,
            "from-seq": 0,
            "to-seq": len(chain) - 1,
            "head-hash": head,
            "count": len(chain),
            "at": "2026-07-26T10:00:00.000Z",
        }
        body.update(over)
