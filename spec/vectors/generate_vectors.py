def mandate(
    kind: str,
    grantor: Key,
    grantor_role: str,
    grantee: Key,
    *,
    not_before: str = T_MANDATE_ISSUE,
    not_after: str | None = T_MANDATE_EXPIRY,
    parent: str | None = None,
    max_depth: int = 2,
    actions: list[str] | None = None,
    components: list[str] | None = None,
    classes: list[str] | None = None,
    resources: list[str] | None = None,
    nonce: str | None = None,
    drop: list[str] | None = None,
) -> dict:
    obj = {
        "v": V,
        "kind": "mandate",
        "mandate-kind": kind,
        "grantor": {"subject": grantor.label, "key": grantor.key_id, "role": grantor_role},
        "grantee": {"subject": grantee.label, "key": grantee.key_id},
        "issued-at": T_MANDATE_ISSUE,
        "not-before": not_before,
        "not-after": not_after,
        "parent": parent,
        "max-depth": max_depth,
        "scope": {
            "components": components if components is not None else ["gateway"],
            "actions": actions if actions is not None else ["github.*"],
            "classes": classes if classes is not None else ["read", "benign", "consequential"],
            "resources": resources if resources is not None else ["repo:acme/backend"],
        },
        "budget": {"requests": 5000, "money-eur": "25.00"},
        "nonce": nonce or sha256_hex((kind + grantor.label + grantee.label + str(parent)).encode())[:32],
    }
    for k in drop or []:
        obj.pop(k, None)
    return sign_object(obj, grantor)


